H("1.2. Дрейф (точный, δ-корректный)", 2)
P("Между воздействиями поля частица летит по прямой. Точный симплектический дрейф на длину ℓ:")
EQ(r"p_s=\sqrt{(1+\delta)^2-p_x^2-p_y^2}")
EQ(r"x\to x+\ell\,\frac{p_x}{p_s},\quad y\to y+\ell\,\frac{p_y}{p_s},\quad t\to t+\ell\,\frac{1+\delta}{p_s}")
