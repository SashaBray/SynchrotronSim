def facts():
    """Всё, что документ говорит о размерах и точности, — посчитано здесь, а не переписано."""
    import branch_network as bn
    import mec_sigma as ms

    out = {"elements": {}, "orders": {}}
    for el in ELEMENTS:
        cir = bn.Circuit(el)
        d = dict(branches=len(cir.branches), nodes=len(cir.nodes),
                 iron=len(cir.iron), gaps=len(cir.gaps),
                 len_classes=len(cir.len_classes), gap_classes=len(cir.gap_classes),
                 coils=len(cir.coil_branches), coil_names=sorted(cir.coil_branches),
                 geom=cir.geom is not None)
        if cir.geom is not None:
            names = ms.kick_names(cir)
            d["kick_classes"] = len(names)
            d["kick_names"] = names
            d["kick_branches"] = sum(1 for b in cir.gaps if cir.sym[b] in cir.kick_classes)
        out["elements"][el] = d

    for el, n in ms.MODELS:
        out["orders"].setdefault(el, []).append(n)

    # свободные числа подгонки, по элементам
    fits = {}
    for r in csv.DictReader((l for l in io.open(FITS, encoding="utf-8-sig") if not l.startswith("#")),
                            delimiter=";"):
        fits.setdefault(r["section"], []).append(r)
    out["fits"] = fits

    # достигнутая точность: комбинации — независимая проверка
    saved = ms.load()
    acc = {}
    for el in GRAPH_ELEMENTS:
        for n in out["orders"].get(el, []):
            cir, w = saved[(el, n)]
            maps = bn.read_maps(el, n)
            row = {}
            for lbl, grp in (("одиночные", [t for t in maps if len(t[0]) == 1]),
                             ("комбинации", [t for t in maps if len(t[0]) > 1])):
                num = sum(abs(complex(ms.basis(cir, c) @ w) - m) for c, m, _, _ in grp)
                den = sum(abs(m) for c, m, _, _ in grp)
                e, miss = ms.current_errors(el, n, grp, saved)
                row[lbl] = dict(kick=100 * num / den, n=len(grp),
                                cur=(float(np.mean(e)) if e else float("nan")), miss=miss)
            acc[(el, n)] = row
    out["acc"] = acc
    return out


