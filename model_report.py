def ch_accuracy(doc, F, lo):
    doc.add_heading("11. Достигнутая точность", level=1)
    doc.add_paragraph(
        "Веса подгоняются ТОЛЬКО по картам с одной возбуждённой обмоткой. Карты, где обмотки "
        "работают вместе, в подгонку не входят ни разу и потому служат независимой проверкой: на "
        "них модель именно предсказывает.")
    doc.add_paragraph(
        "Приводятся две метрики. Первая — расхождение по кику, сумма модулей разностей к сумме "
        "модулей измеренного; она считается по всем картам. Вторая — ошибка по току: во сколько "
        "раз пришлось бы изменить ток, чтобы модель дала измеренный кик. Вторая жёстче первой, "
        "потому что в насыщении отклик пологий и промах в кике на процент означает промах в токе "
        "в несколько раз больший. У неё есть особенность, о которой надо помнить: если модель не "
        "дотягивается до измеренного кика ни при каком токе, решения не существует, и такая карта "
        "в среднее не попадает вовсе. Поэтому рядом с ошибкой указан охват.")
    rows = []
    NAME = {1: "B", 2: "G", 3: "S"}
    for (el, n), row in sorted(F["acc"].items()):
        s, c = row["одиночные"], row["комбинации"]
        rows.append([el, NAME.get(n, n),
                     f'{s["kick"]:.1f}', f'{s["cur"]:.1f}', f'{s["n"] - s["miss"]}/{s["n"]}',
                     f'{c["kick"]:.1f}', f'{c["cur"]:.1f}', f'{c["n"] - c["miss"]}/{c["n"]}'])
    _table(doc, ["Элемент", "Гарм.", "кик, %", "ток, %", "охват",
                 "кик, %", "ток, %", "охват"], rows,
           caption="Точность на одиночных обмотках (подгонка) и на комбинациях (проверка)")
    doc.add_paragraph(
        "Разница между диполем-квадруполем и корректором объясняется не устройством модели — она "
        "одна и та же, — а плотностью данных: на обмотку диполя-квадруполя приходится вдвое "
        "больше карт, чем на обмотку корректора.")
    _pic(doc, os.path.join(FIGS, "DQ_combinations_check.png"), 16.0,
         "Диполь-квадруполь: предсказание против измерения на комбинациях обмоток. "
         "Комбинации в подгонку не входили")
    _pic(doc, os.path.join(FIGS, "corrector_combinations_check.png"), 16.5,
         "Корректор: то же для шести составляющих кика. Точки на краях лежат внутри прямой — "
         "модель занижает величину и по плюсу, и по минусу")


