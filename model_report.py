def _formula(doc, latex, lo):
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    lo.add_formula(p, latex)
    return p


def _vars(doc, triples):
    """Расшифровка обозначений: висячий отступ, «— символ — смысл; тип, единицы»."""
    from docx.shared import Cm, Pt
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    for sym, kind, txt in triples:
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(1.0)
        p.paragraph_format.first_line_indent = Cm(-1.0)
        p.paragraph_format.space_after = Pt(2)
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.add_run("— ")
        p.add_run(sym).italic = True
        p.add_run(f" — {txt}; {kind}.")
    doc.add_paragraph()


def _tcap(doc, text):
    from docx.shared import Pt
    _tcap.n = getattr(_tcap, "n", 0) + 1
    p = doc.add_paragraph()
    r = p.add_run(f"Таблица {_tcap.n}. {text}")
