def _table(doc, header, rows, caption=None, pt=9):
    from docx.shared import Pt
    if caption:
        _tcap(doc, caption)
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Light Grid Accent 1"
    for i, h in enumerate(header):
        t.rows[0].cells[i].text = h
    for row in rows:
        c = t.add_row().cells
        for i, v in enumerate(row):
            c[i].text = str(v)
    for row in t.rows:
        for cell in row.cells:
            for par in cell.paragraphs:
                for run in par.runs:
                    run.font.size = Pt(pt)
    doc.add_paragraph()


def _pic(doc, path, cm=16.0, caption=None):
    from docx.shared import Cm
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    if not os.path.exists(path):
        return
    doc.add_picture(path, width=Cm(cm))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    if caption:
        _fcap(doc, caption)


def _body_format(doc):
    from docx.shared import Cm
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    for p in doc.paragraphs:
        if not p.text.strip() or p.style.name.startswith("Heading") or p.style.name == "Title":
            continue
        if p.alignment == WD_ALIGN_PARAGRAPH.CENTER or p.text.startswith("— "):
            continue
        p.paragraph_format.first_line_indent = Cm(1.25)
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


