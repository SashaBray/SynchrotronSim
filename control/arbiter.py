# -*- coding: utf-8 -*-
"""Arbiter — настраиваемый слой СБОРКИ КОМАНДЫ между контурами и установкой (зеркало Observer'а).

Контуры пишут свои СЛОТЫ target (по одному на контур). `Arbiter` собирает из них единый ТРЕБУЕМЫЙ
вектор машинного состояния, который планировщик отдаёт в `Limits`→plant. По умолчанию — РОВНО прежнее
поведение: config + Σ слотов (`state.effective_target()`), без преобразований и без выгрузки наружу.

Три точки расширения (пока заглушки — каждая отдельным инкрементом потом):
  • combine — ЗАКОН объединения слотов: не только сумма, но приоритеты / мёртвые зоны / развязка
              каналов / перераспределение по избыточным актуаторам;
  • stages  — КОНВЕЙЕР преобразований требуемого вектора: сюда ляжет модель токов
              (требуемое поле → ток (обратная модель магнита) → реализованное поле (прямая,
              с насыщением / feed-down) — опирается на наш граф ветвей / насыщение);
  • sink    — ВЫГРУЗКА состояния наружу (клиентскому приложению): `publish(state)`, дефолт no-op
              (позже WebSocket / IPC — единая точка, откуда клиент видит команды + наблюдаемые).

Слои: plant (сырьё) → Observer (сборка наблюдаемых) → контуры → Arbiter (сборка команды) → Limits → plant.
Пользователь кастомизирует combine / stages / sink, не трогая диффур-ядро, планировщик и контуры.
"""


class Arbiter:
    """Сборщик управляющей команды. Дефолт воспроизводит сумму по слотам бит-в-бит.

      combine=None → `state.effective_target()` (config + Σ слотов);
      stages=()    → список fn(state, req)->req (преобразования требуемого вектора; напр. модель токов);
      sink=None    → `publish` — no-op (позже: выгрузка клиенту).

    Кастомизация — своими combine / stages / sink: это «обёртка, где пишешь логику команды», симметрично
    тому, как Observer — «обёртка, где пишешь логику данных»."""

    def __init__(self, combine=None, stages=None, sink=None):
        self._combine = combine
        self.stages = list(stages or [])
        self._sink = sink

    def combine(self, state):
        """Единый требуемый вектор машины: базовое объединение слотов → конвейер преобразований."""
        req = self._combine(state) if self._combine is not None else state.effective_target()
        for stage in self.stages:
            req = stage(state, req)
        return req

    def publish(self, state):
        """Выгрузить состояние наружу (команды + наблюдаемые). Дефолт — ничего не делает."""
        if self._sink is not None:
            self._sink(state)
