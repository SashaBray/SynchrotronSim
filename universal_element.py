"""Универсальный мультипольный элемент: каждый магнит = combined-function со ВСЕМИ
мультиполями одновременно — горизонтальный диполь (θy), вертикальный диполь (θz),
квадруполь (k1), секступоль (k2), октуполь (k3). Физкоэффициент каждого мультиполя
линеен по входу (ток/коэф.); матрица связи «вход → (θy,θz,k1,k2,k3)» подбирается по
траекториям Boris.

Трекер РАСПРЕДЕЛЁННЫЙ (nsl срезов): на каждом срезе — точный линейный перенос
(κy=k1+θy²/L², κz=−k1+θz²/L², матрицы cos/sin — bm._plane) + дипольные и нелинейные
кики в центре среза. Распределённость нужна, чтобы feed-down (при изгибе орбита уходит
off-axis, высшие мультиполи действуют на смещённую орбиту) копился вдоль траектории.

Соглашение (как в bip_matrix): y''=−(q/p)Bz, z''=+(q/p)By; Bz+iBy=Σ Cn(y+iz)^(n−1).
  диполь   : Bz0,By0                → θy=−(q/p)Bz0·L, θz=+(q/p)By0·L
  квадруп. : Bz=G·y, By=G·z         → k1=(q/p)G
  секступ. : Bz=(S/2)(y²−z²),By=S·yz→ k2=(q/p)S,  Δy'=−½k2(y²−z²), Δz'=k2·yz
  октуполь : Bz=(O/6)(y³−3yz²)…     → k3=(q/p)O,  Δy'=−(k3/6)(y³−3yz²), Δz'=(k3/6)(3y²z−z³)
"""
import bip_matrix as bm

_plane = bm._plane
QP = bm.QP
# порядок вектора силы: нормальные (θy,θz,k1,k2,k3) + СКЬЮ (45°-повёрнутые): ks1 квад, ks2 секступ., ks3 окт.
STRENGTH_NAMES = ("θy", "θz", "k1", "k2", "k3", "ks1", "ks2", "ks3")


def track(init_yz, ty, tz, k1, k2, k3, L, d1, d2, nsl=40, ks1=0.0, ks2=0.0, ks3=0.0, aper=None):
    """Финальные (Y,Y',Z,Z') для набора начальных (y0,z0). ty,tz — полные углы изгиба (рад);
    k1,k2,k3 — плотности НОРМАЛЬНОЙ силы (1/м²,1/м³,1/м⁴); ks1,ks2,ks3 — СКЬЮ (повёрнутые
    мультиполи, связывают плоскости y↔z). Нормальный квадруполь — в точном лин. переносе (κ),
    скью и нелинейные — распределённые кики. aper — полу-апертура (м): за ней поля нет (чистый
    дрейф), как в реальной карте; None = без апертуры (точная обратная совместимость)."""
    ds = L / nsl
    kay = k1 + (ty * ty) / (L * L)      # κy: нормальный квадруполь + геом. фокус гориз. изгиба
    kaz = -k1 + (tz * tz) / (L * L)     # κz: дефокус квадруполя + геом. фокус верт. изгиба
    out = []
    for (Y0, Z0) in init_yz:
        Y, Yp, Z, Zp = Y0, 0.0, Z0, 0.0
        Y += Yp * d1; Z += Zp * d1                       # дрейф до элемента
        for _ in range(nsl):
            if aper is not None and (abs(Y) > aper or abs(Z) > aper):
                Y += Yp * ds; Z += Zp * ds               # вне апертуры — поля нет, чистый дрейф
                continue
            Y, Yp = _plane(Y, Yp, kay, ds / 2); Z, Zp = _plane(Z, Zp, kaz, ds / 2)
            # нормальные кики (изгиб, секступоль, октуполь)
            Yp += ty / nsl - 0.5 * k2 * (Y * Y - Z * Z) * ds - (k3 / 6.0) * (Y ** 3 - 3 * Y * Z * Z) * ds
            Zp += tz / nsl + k2 * Y * Z * ds + (k3 / 6.0) * (3 * Y * Y * Z - Z ** 3) * ds
            # скью кики (45°-повёрнутые): квад связь y↔z, секступ./окт. с переставленным ядром
            Yp += ks1 * Z * ds + ks2 * Y * Z * ds + (ks3 / 6.0) * (3 * Y * Y * Z - Z ** 3) * ds
            Zp += ks1 * Y * ds + 0.5 * ks2 * (Y * Y - Z * Z) * ds + (ks3 / 6.0) * (Y ** 3 - 3 * Y * Z * Z) * ds
            Y, Yp = _plane(Y, Yp, kay, ds / 2); Z, Zp = _plane(Z, Zp, kaz, ds / 2)
        Y += Yp * d2; Z += Zp * d2                       # дрейф после элемента
        out.append((Y, Yp, Z, Zp))
    return out


def phys_from_strength(ty, tz, k1, k2, k3, L, ks1=0.0, ks2=0.0, ks3=0.0):
    """Вектор силы → физические мультиполи на единицу входа: нормальные Bz0,By0 [Тл], G [Тл/м],
    S [Тл/м²], O [Тл/м³] + скью Gs,Ss,Os (для читаемости матрицы связи)."""
    return dict(Bz0=-ty / (QP * L), By0=tz / (QP * L), G=k1 / QP, S=k2 / QP, O=k3 / QP,
                Gs=ks1 / QP, Ss=ks2 / QP, Os=ks3 / QP)
